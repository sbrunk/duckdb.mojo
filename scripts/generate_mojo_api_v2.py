# Extension API struct layout
# ---------------------------------------------------------------------------

def _current_state(fn: dict) -> list:
    # The first lifecycle entry is the current state.
    return fn["lifecycle"][0]


def _stable_since(fn: dict) -> str | None:
    versions = [v for state, v, *_ in fn["lifecycle"] if state == "stable"]
    return min(versions, key=Version) if versions else None


def ext_api_layout(spec: Spec) -> tuple[list[dict], list[str]]:
    """Return the stable bands and the unstable tail of ``duckdb_ext_api_v2``.

    Stable functions have an ``offset`` and sit at that position, grouped into
    bands by the version in which they became stable (raised to the spec's
    ``version_floor``). Everything that is still unstable follows, ordered by
    the date of its current lifecycle entry and then by name. That is the
    order DuckDB's generator uses; ``check_layout`` verifies it.
    """
    floor = Version(spec.metadata["version_floor"])
    stable = sorted((f for f in spec.functions if "offset" in f), key=lambda f: f["offset"])
    if [f["offset"] for f in stable] != list(range(len(stable))):
        raise ValueError("V2 extension API offsets are not contiguous")
    bands: list[dict] = []
    for fn in stable:
        since = _stable_since(fn)
        if since is None:
            raise ValueError(f"{fn['name']} has a struct slot but was never stable")
        version = "v" + str(max(Version(since), floor))
        if bands and Version(version) < Version(bands[-1]["version"]):
            raise ValueError(f"{fn['name']} is out of version order in the struct")
        if not bands or bands[-1]["version"] != version:
            bands.append({"version": version, "entries": []})
        bands[-1]["entries"].append(fn["name"])

    unplaced = [f for f in spec.functions if "offset" not in f]
    for fn in unplaced:
        if _current_state(fn)[0] != "unstable":
            raise ValueError(
                f"{fn['name']} is {_current_state(fn)[0]} but has no offset: the generator does not know its slot"
            )
    unstable = [f["name"] for f in sorted(unplaced, key=lambda f: (str(_current_state(f)[2]), f["name"]))]
    return bands, unstable


def enum_values(spec: Spec) -> list[tuple[str, int]]:
    """Every enum value as (C name, number). As in C, a value without an
    explicit number is the previous one plus one."""
    out: list[tuple[str, int]] = []
    for module in spec.modules:
        for decl in (module.get("enums") or {}).values():
            next_value = 0
            for value_name, value in decl["values"].items():
                number = value.get("value", next_value)
                next_value = number + 1
                out.append((spec.prefix.upper() + value_name, number))
    return out


def check_layout(duckdb_dir: str, spec: Spec, bands: list[dict], unstable: list[str]) -> None:
    """Check the struct layout and the function signatures against DuckDB's headers."""
    with open(os.path.join(duckdb_dir, EXT_HEADER)) as f:
        ext_header = f.read()
    m = re.search(r"typedef struct \{(.*?)\} duckdb_ext_api_v2;", ext_header, re.DOTALL)
    if m is None:
        raise ValueError(f"duckdb_ext_api_v2 not found in {EXT_HEADER}")
    body = m.group(1)
    expected = re.findall(r"\(\*(\w+)\)", body)
    stable = [name for band in bands for name in band["entries"]]
    actual = stable + unstable
    if expected != actual:
        first = next((i for i, (a, b) in enumerate(zip(expected, actual)) if a != b), min(len(expected), len(actual)))
        raise ValueError(
            f"V2 extension API struct layout differs from {EXT_HEADER} "
            f"({len(actual)} fields generated, {len(expected)} in the header, first difference at {first})"
        )
    # Everything after the unstable guard is the unstable tail.
    guard = body.find("#if DUCKDB_V2_API_ALLOW_UNSTABLE")
    stable_in_header = len(re.findall(r"\(\*(\w+)\)", body[:guard])) if guard >= 0 else len(expected)
    if stable_in_header != len(stable):
        raise ValueError(
            f"{EXT_HEADER} has {stable_in_header} stable fields, the spec {len(stable)}"
        )

    with open(os.path.join(duckdb_dir, C_HEADER)) as f:
        c_header = f.read()
    prototypes = {
        name: params
        for name, params in re.findall(r"DUCKDB_C_API[^;(]*?\b(duckdb_v2_\w+)\(([^;]*)\);", c_header, re.DOTALL)
    }
    # Enum values, including the ones the spec numbers implicitly.
    header_values = {name: int(value, 0) for name, value in re.findall(r"\b(DUCKDB_V2_\w+) = (-?(?:0x)?[0-9A-Fa-f]+),", c_header)}
    for name, value in enum_values(spec):
        if header_values.get(name) != value:
            raise ValueError(f"enum value {name} is {value} in the spec, {header_values.get(name)} in {C_HEADER}")

    for fn in spec.functions:
        if fn["name"] not in prototypes:
            raise ValueError(f"{fn['name']} not found in {C_HEADER}")
        params = prototypes[fn["name"]].strip()
        count = 0 if params in ("", "void") else params.count(",") + 1
        if count != len(fn.get("parameters") or {}):
            raise ValueError(
                f"{fn['name']} has {len(fn.get('parameters') or {})} parameters in the spec, {count} in {C_HEADER}"
            )


