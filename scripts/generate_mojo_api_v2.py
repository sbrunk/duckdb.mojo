def duckdb_source_version(duckdb_dir: str) -> str:
    """The DuckDB release the source tree is at, e.g. `v2.0.0`."""
    try:
        out = subprocess.run(
            ["git", "-C", duckdb_dir, "describe", "--tags", "--always"],
            capture_output=True, text=True, check=True,
        )
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def gen_header(spec: Spec, duckdb_version: str, bands: list[dict]) -> list[str]:
    api_version = "v" + str(max(Version(v) for v in spec.metadata["versions"]))
    stable_version = bands[-1]["version"] if bands else spec.metadata["version_floor"]
    return [
        "# ===--------------------------------------------------------------------===#",
        "# FFI definitions for DuckDB's V2 C API (duckdb_v2.h) ported to Mojo.",
        "#",
        "# WARNING: this file is autogenerated by scripts/generate_mojo_api_v2.py",
        "# Manual changes will be overwritten!",
        "# ===--------------------------------------------------------------------===#",
        "",
        "from std.ffi import c_char, UnsafeUnion",
        "from std.os import abort",
        "from std.memory import Pointer",
        "from duckdb._libduckdb import idx_t, _dylib_function",
        "",
        f'comptime DUCKDB_V2_SOURCE_VERSION = "{duckdb_version}"',
        '"""The DuckDB release these bindings were generated from.',
        "",
        "The unstable part of the V2 API may change in any release, so it only",
        'matches a libduckdb of exactly this version."""',
        "",
        f'comptime DUCKDB_V2_API_VERSION = "{api_version}"',
        '"""The newest V2 API version the spec describes."""',
        "",
        f'comptime DUCKDB_V2_EXTENSION_API_VERSION = "{stable_version}"',
        '"""The V2 extension API version whose stable functions make up `duckdb_ext_api_v2`."""',
        "",
    ]


def gen_types(spec: Spec) -> list[str]:
    out: list[str] = []
    numbers = dict(enum_values(spec))

    out += [format_section_header("General types"), ""]
    out += [
        "# The extension being loaded. DuckDB passes it to the extension entrypoint.",
        "struct _duckdb_v2_extension_info:",
        "    var internal_ptr: Pointer[NoneType, MutUntrackedOrigin]",
        f"comptime {EXTENSION_HANDLE} = Pointer[_duckdb_v2_extension_info, MutUntrackedOrigin]",
        "",
    ]
    out += gen_arrow_structs()

    for module in spec.modules:
        section_lines: list[str] = []

        for name, decl in (module.get("enums") or {}).items():
            enum = spec.mojo_name(name)
            section_lines += comment_block(spec, decl.get("description", ""), "#!")
            section_lines.append(f"comptime {enum} = Int32")
            for value_name, value in decl["values"].items():
                c_name = spec.prefix.upper() + value_name
                section_lines += comment_block(spec, value.get("description", ""))
                section_lines.append(f"comptime {c_name}: {enum} = {numbers[c_name]}")
            section_lines.append("")

        for name, decl in (module.get("constants") or {}).items():
            section_lines += comment_block(spec, decl.get("description", ""), "#!")
            section_lines.append(f"comptime {spec.prefix.upper()}{name} = {decl['value']}")
            section_lines.append("")

        for name, decl in (module.get("handles") or {}).items():
            tag = f"_{spec.prefix}{name}"
            section_lines += comment_block(spec, decl.get("description", ""), "#!")
            section_lines.append(f"struct {tag}:")
            section_lines.append("    var internal_ptr: Pointer[NoneType, MutUntrackedOrigin]")
            section_lines.append(f"comptime {spec.mojo_name(name)} = Pointer[{tag}, MutUntrackedOrigin]")
            section_lines.append("")

        for name, decl in (module.get("aliases") or {}).items():
            section_lines += comment_block(spec, decl.get("description", ""), "#!")
            section_lines.append(f"comptime {spec.mojo_name(name)} = {spec.mojo_name(decl['underlying'])}")
            section_lines.append("")

        for name, decl in (module.get("callbacks") or {}).items():
            section_lines += comment_block(spec, decl.get("description", ""), "#!")
            section_lines.append(f"comptime {spec.mojo_name(name)} = {fn_pointer_type(spec, decl, role='foreign')}")
            section_lines.append("")

        for name, decl in (module.get("structs") or {}).items():
            section_lines += gen_struct(spec, spec.mojo_name(name), decl.get("fields") or [], decl.get("description", ""))

        if section_lines:
            out += [format_section_header(f"Types: {headline_capitalize(module['module'])}"), ""]
            out += section_lines
    return out


def struct_field_type(spec: Spec, field: dict) -> str:
    t = mojo_type(spec, field["type"], field.get("pointer", 0), field.get("const", False), role="foreign")
    if "array_size" in field:
        t = f"Array[{t}, {field['array_size']}]"
    return t


def gen_struct(spec: Spec, name: str, fields: list[dict], description: str) -> list[str]:
    """Emit a struct. A union field becomes an `UnsafeUnion` of one struct per member."""
    out: list[str] = []
    members: list[tuple[str, str, str]] = []  # (name, type, description)
    for field in fields:
        if "union" in field:
            variants = []
            for variant in field["union"]:
                vname = f"{name}_{variant['name']}"
                out += gen_struct(spec, vname, variant["fields"], "")
                variants.append(vname)
            members.append((field["name"], f"UnsafeUnion[{', '.join(variants)}]", field.get("description", "")))
        else:
            members.append((field["name"], struct_field_type(spec, field), field.get("description", "")))

    out += comment_block(spec, description, "#!")
    out.append("@fieldwise_init")
    out.append(f"struct {name}(Copyable, Movable):")
    for fname, ftype, fdesc in members:
        out.append(f"    var {fname}: {ftype}")
        out += docstring(spec, "    ", fdesc)
    out.append("")
    return out


def gen_arrow_structs() -> list[str]:
    """The Arrow C data and stream interface structs (as in duckdb_v2.h)."""
    return [
        "#! Arrow C Data Interface: a schema (https://arrow.apache.org/docs/format/CDataInterface.html).",
        "struct ArrowSchema:",
        "    var format: Pointer[c_char, ImmUntrackedOrigin]",
        "    var name: Pointer[c_char, ImmUntrackedOrigin]",
        "    var metadata: Pointer[c_char, ImmUntrackedOrigin]",
        "    var flags: Int64",
        "    var n_children: Int64",
        "    var children: Pointer[Pointer[ArrowSchema, MutUntrackedOrigin], MutUntrackedOrigin]",
        "    var dictionary: Pointer[ArrowSchema, MutUntrackedOrigin]",
        '    var release: def(Pointer[ArrowSchema, MutUntrackedOrigin]) thin abi("C") -> NoneType',
        "    var private_data: Pointer[NoneType, MutUntrackedOrigin]",
        "",
        "#! Arrow C Data Interface: an array.",
        "struct ArrowArray:",
        "    var length: Int64",
        "    var null_count: Int64",
        "    var offset: Int64",
        "    var n_buffers: Int64",
        "    var n_children: Int64",
        "    var buffers: Pointer[Pointer[NoneType, ImmUntrackedOrigin], MutUntrackedOrigin]",
        "    var children: Pointer[Pointer[ArrowArray, MutUntrackedOrigin], MutUntrackedOrigin]",
        "    var dictionary: Pointer[ArrowArray, MutUntrackedOrigin]",
        '    var release: def(Pointer[ArrowArray, MutUntrackedOrigin]) thin abi("C") -> NoneType',
        "    var private_data: Pointer[NoneType, MutUntrackedOrigin]",
        "",
        "#! Arrow C Stream Interface: a stream of arrays.",
        "struct ArrowArrayStream:",
        '    var get_schema: def(Pointer[ArrowArrayStream, MutUntrackedOrigin], Pointer[ArrowSchema, MutUntrackedOrigin]) thin abi("C") -> Int32',
        '    var get_next: def(Pointer[ArrowArrayStream, MutUntrackedOrigin], Pointer[ArrowArray, MutUntrackedOrigin]) thin abi("C") -> Int32',
        '    var get_last_error: def(Pointer[ArrowArrayStream, MutUntrackedOrigin]) thin abi("C") -> Pointer[c_char, ImmUntrackedOrigin]',
        '    var release: def(Pointer[ArrowArrayStream, MutUntrackedOrigin]) thin abi("C") -> NoneType',
        "    var private_data: Pointer[NoneType, MutUntrackedOrigin]",
        "",
    ]


def gen_ext_api_structs(spec: Spec, bands: list[dict], unstable: list[str]) -> list[str]:
    by_name = {f["name"]: f for f in spec.functions}
    stable = [(band["version"], name) for band in bands for name in band["entries"]]

    def fields(entries: list[tuple[str, str]]) -> list[str]:
        lines: list[str] = []
        current = None
        for band, name in entries:
            if band != current:
                lines += ["", f"    # --- {band} ---"]
                current = band
            lines.append(f"    var {name}: {fn_pointer_type(spec, by_name[name], role='param')}")
        return lines

    out = [format_section_header("Extension API structs"), ""]
    out += [
        "@fieldwise_init",
        "struct duckdb_ext_api_v2:",
        '    """The stable part of the V2 extension API function pointer struct.',
        "",
        f"    Holds the functions that are stable as of `DUCKDB_V2_EXTENSION_API_VERSION`",
        f"    ({len(stable)} function pointers). An extension that only uses these loads",
        '    in that DuckDB version and every later 2.x release."""',
    ]
    out += fields(stable) if stable else ["", "    # No V2 function is stable yet.", "    pass"]
    out += ["", ""]
    out += [
        "@fieldwise_init",
        "struct duckdb_ext_api_v2_unstable:",
        '    """The complete V2 extension API function pointer struct, including the unstable part.',
        "",
        f"    Holds {len(stable) + len(unstable)} function pointers. The unstable part may change in",
        "    any release, so an extension that uses it only loads in the exact DuckDB",
        '    version these bindings were generated from (`DUCKDB_V2_SOURCE_VERSION`)."""',
    ]
    out += fields(stable + [("unstable", name) for name in unstable])
    out.append("")
    return out


def gen_libduckdb_struct(spec: Spec, stable_names: set[str]) -> list[str]:
    names = [f["name"] for f in spec.functions]
    out = [format_section_header("LibDuckDBV2"), ""]
    out.append("struct LibDuckDBV2(Movable):")
    out.append('    """The V2 C API functions, loaded from libduckdb or from an extension API struct."""')
    out.append("")
    for name in names:
        out.append(f"    var _{name}: _{name}.fn_type")
    out.append("")

    out.append("    def __init__(out self) raises:")
    out.append('        """Client mode: look up every function in libduckdb with dlsym.')
    out.append("")
    out.append("        Raises if libduckdb lacks one of them, for example because it is")
    out.append('        not the DuckDB version these bindings were generated from."""')
    for name in names:
        out.append(f"        self._{name} = _{name}.load()")
    out.append("")

    out.append("    def __init__(out self, api: Pointer[duckdb_ext_api_v2_unstable, ImmUntrackedOrigin]):")
    out.append('        """Extension mode, pinned to the exact DuckDB version: every function comes from the struct."""')
    for name in names:
        out.append(f"        self._{name} = api[].{name}")
    out.append("")

    out.append("    def __init__(out self, api: Pointer[duckdb_ext_api_v2, ImmUntrackedOrigin]):")
    out.append('        """Extension mode, stable API: stable functions come from the struct.')
    out.append("")
    out.append("        The unstable ones are bound to stubs that abort when called, so the")
    out.append('        extension still loads as long as it does not use them."""')
    for name in names:
        source = f"api[].{name}" if name in stable_names else f"_unstable_{name}"
        out.append(f"        self._{name} = {source}")
    out.append("")

    out.append("    def __init__(out self, *, deinit move: Self):")
    for name in names:
        out.append(f"        self._{name} = move._{name}")
    out.append("")

    for module in spec.modules:
        fns = [f for f in spec.functions if f["module"] == module["module"]]
        if not fns:
            continue
        out.append(format_comment_header(headline_capitalize(module["module"])))
        for fn in fns:
            out += gen_method(spec, fn)
            out.append("")
    return out


def gen_method(spec: Spec, fn: dict) -> list[str]:
    """A wrapper method. Pointer parameters are generic over their origin."""
    origin_params: list[str] = []
    sig: list[str] = []
    args: list[str] = []
    arg_docs: list[tuple[str, str]] = []
    for raw_name, p in (fn.get("parameters") or {}).items():
        name = param_name(raw_name)
        t = mojo_type(spec, p["type"], p.get("indirection", 0), p.get("const", False), role="param")
        arg = name
        split = split_pointer_origin(t)
        if split is not None and split[1] in ERASED_ORIGINS:
            origin = f"{name}_origin"
            origin_params.append(f"{origin}: {ERASED_ORIGINS[split[1]]}")
            t = f"Pointer[{split[0]}, {origin}]"
            arg = f"{name}.as_unsafe_any_origin()"
        sig.append(f"        {name}: {t},")
        args.append(arg)
        arg_docs.append((name, p.get("description", "")))

    params = f"[{', '.join(origin_params)}]" if origin_params else ""
    out = [f"    def {fn['name']}{params}(", "        self,"] + sig + [f"    ) -> {return_type(spec, fn)}:"]
    out += docstring(spec, "        ", fn.get("description", ""), arg_docs)
    out.append(f"        return self._{fn['name']}({', '.join(args)})")
    return out


def gen_dylib_declarations(spec: Spec) -> list[str]:
    out = [format_section_header("Function declarations"), ""]
    for fn in spec.functions:
        out.append(f'comptime _{fn["name"]} = _dylib_function["{fn["name"]}",')
        out.append(f"    {fn_pointer_type(spec, fn, role='param')}")
        out.append("]")
        out.append("")
    return out


def gen_unstable_stubs(spec: Spec, stable_names: set[str]) -> list[str]:
    fns = [f for f in spec.functions if f["name"] not in stable_names]
    if not fns:
        return []
    out = [format_section_header("Stubs for unstable functions (stable extension API)"), ""]
    for fn in fns:
        params = ", ".join(
            f"a{i}: {mojo_type(spec, p['type'], p.get('indirection', 0), p.get('const', False), role='param')}"
            for i, p in enumerate((fn.get("parameters") or {}).values())
        )
        out.append(f'def _unstable_{fn["name"]}({params}) abi("C") -> {return_type(spec, fn)}:')
        out.append(f'    abort("{fn["name"]} is not part of the stable V2 extension API")')
        out.append("")
    return out


def generate(duckdb_dir: str) -> str:
    spec = Spec(duckdb_dir)
    bands, unstable = ext_api_layout(spec)
    check_layout(duckdb_dir, spec, bands, unstable)
    stable_names = {name for band in bands for name in band["entries"]}
    print(
        f"V2 API: {len(spec.functions)} functions, {len(stable_names)} stable, {len(unstable)} unstable",
        file=sys.stderr,
    )

    out: list[str] = []
    out += gen_header(spec, duckdb_source_version(duckdb_dir), bands)
    out += gen_types(spec)
    out += gen_ext_api_structs(spec, bands, unstable)
    out += gen_libduckdb_struct(spec, stable_names)
    out += gen_dylib_declarations(spec)
    out += gen_unstable_stubs(spec, stable_names)
    return "\n".join(out).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description="Generate Mojo bindings for DuckDB's V2 C API")
    parser.add_argument(
        "--duckdb-dir",
        default="third_party/duckdb",
        help="Path to the DuckDB source tree (default: the third_party/duckdb submodule)",
    )
    parser.add_argument("--output", default=OUTPUT_FILE, help=f"Output file path (default: {OUTPUT_FILE})")
    args = parser.parse_args()

    duckdb_dir = os.path.abspath(args.duckdb_dir)
    workspace_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    if not os.path.isfile(os.path.join(duckdb_dir, API_SPEC_METADATA)):
        print(f"ERROR: no V2 API spec at {os.path.join(duckdb_dir, API_SPEC_METADATA)}", file=sys.stderr)
        sys.exit(1)

    output_path = os.path.join(workspace_dir, args.output)
    with open(output_path, "w") as f:
        f.write(generate(duckdb_dir))
    print(f"Generated {output_path}")


if __name__ == "__main__":
    main()
