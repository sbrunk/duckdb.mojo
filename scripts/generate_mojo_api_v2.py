#!/usr/bin/env python3
"""Generate Mojo bindings for DuckDB's V2 C API.

DuckDB 2.0 ships a second C API ("V2", prefix ``duckdb_v2_``), described by the
YAML spec in ``api_spec/v2``. This script turns that spec into
``duckdb/_libduckdb_v2.mojo``. Unlike the V1 generator, which writes most types
by hand, everything here comes from the spec: handles, enums, constants,
structs, aliases, callbacks and functions.

The output has:
- the types of the spec,
- ``duckdb_ext_api_v2`` (the stable part of the extension function pointer
  struct) and ``duckdb_ext_api_v2_unstable`` (all of it),
- ``LibDuckDBV2``, with one wrapper method per function. It loads the
  functions with dlsym (client mode) or from one of the two structs
  (extension mode).

The struct layout is checked against DuckDB's ``duckdb_extension_v2.h`` and the
parameter count of every function against ``duckdb_v2.h``, both generated by
DuckDB from the same spec.

Usage:
    python scripts/generate_mojo_api_v2.py [--duckdb-dir <path>] [--output <file>]
"""

