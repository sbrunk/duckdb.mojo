# ---------------------------------------------------------------------------
# Paths relative to the DuckDB source tree
# ---------------------------------------------------------------------------
API_SPEC_FILES = "api_spec/v2/**/*.yaml"
API_SPEC_METADATA = "api_spec/v2/metadata.yaml"
API_SPEC_EXT_OPTIONS = "api_spec/v2/options/extension_header.yaml"
C_HEADER = "src/include/duckdb_v2.h"
EXT_HEADER = "src/include/duckdb_extension_v2.h"

OUTPUT_FILE = "duckdb/_libduckdb_v2.mojo"

# Mojo keywords and names that cannot be used as parameter names.
MOJO_RESERVED_NAMES = {
    "alias", "and", "as", "assert", "async", "borrowed", "break", "class", "comptime",
    "continue", "def", "deinit", "del", "elif", "else", "except", "False", "finally",
    "fn", "for", "from", "function", "global", "if", "import", "in", "init", "inout",
    "input", "is", "lambda", "let", "mut", "None", "nonlocal", "not", "or", "out",
    "owned", "pass", "raise", "raises", "read", "ref", "return", "Self", "self", "set",
    "struct", "trait", "True", "try", "type", "var", "while", "with", "yield",
}

# Spec primitives that map to Mojo types directly. `extension` and the Arrow
# structs are primitives too, but are emitted as types below.
PRIMITIVES = {
    "void": "NoneType",
    "char": "c_char",
    "bool": "Bool",
    "i8": "Int8",
    "i16": "Int16",
    "i32": "Int32",
    "i64": "Int64",
    "u8": "UInt8",
    "u16": "UInt16",
    "u32": "UInt32",
    "u64": "UInt64",
    "f32": "Float32",
    "f64": "Float64",
    "idx": "idx_t",
    "size": "UInt",
}

# The extension handle is the token DuckDB passes to the entrypoint
# (`struct _duckdb_extension_info *` in C).
EXTENSION_HANDLE = "duckdb_v2_extension_handle"


# ---------------------------------------------------------------------------
# Loading the spec
# ---------------------------------------------------------------------------

class Spec:
    """The parsed V2 spec, with C and Mojo names for every declared type."""

    def __init__(self, duckdb_dir: str):
        with open(os.path.join(duckdb_dir, API_SPEC_METADATA)) as f:
            self.metadata = yaml.safe_load(f)
        with open(os.path.join(duckdb_dir, API_SPEC_EXT_OPTIONS)) as f:
            self.metadata.update(yaml.safe_load(f))
        self.prefix: str = self.metadata["prefix"]
        self.suffixes: dict = self.metadata.get("suffixes", {})

        self.modules: list[dict] = []
        for path in sorted(glob.glob(os.path.join(duckdb_dir, API_SPEC_FILES), recursive=True)):
            if f"{os.sep}options{os.sep}" in path or path.endswith("metadata.yaml"):
                continue
            with open(path) as f:
                data = yaml.safe_load(f)
            if isinstance(data, dict) and "module" in data:
                self.modules.append(data)

        # Spec type name -> (section, Mojo type name)
        self.types: dict[str, tuple[str, str]] = {}
        for name in PRIMITIVES:
            self.types[name] = ("primitive", PRIMITIVES[name])
        self.types["extension"] = ("primitive", EXTENSION_HANDLE)
        for arrow in ("ArrowSchema", "ArrowArray", "ArrowArrayStream"):
            self.types[arrow] = ("primitive", arrow)
        for module in self.modules:
            for section in ("handles", "enums", "structs", "aliases", "callbacks"):
                for name in module.get(section) or {}:
                    if name in self.types:
                        raise ValueError(f"type '{name}' is declared twice in the spec")
                    self.types[name] = (section, self._mojo_type_name(section, name))

        self.functions: list[dict] = []
        for module in self.modules:
            for short, fn in (module.get("functions") or {}).items():
                self.functions.append({"name": self.prefix + short, "module": module["module"], **fn})

    def _mojo_type_name(self, section: str, name: str) -> str:
        if section == "enums":
            return self.prefix.upper() + name
        suffix = {
            "handles": self.suffixes.get("handles", ""),
            "callbacks": self.suffixes.get("callbacks", ""),
            "aliases": self.suffixes.get("aliases", ""),
        }.get(section, "")
        return self.prefix + name + suffix

    def section(self, name: str) -> str:
        return self.types[name][0]

    def mojo_name(self, name: str) -> str:
        if name not in self.types:
            raise ValueError(f"unknown type '{name}' in the V2 API spec")
        return self.types[name][1]


# ---------------------------------------------------------------------------
# Spec types to Mojo types
# ---------------------------------------------------------------------------
#
# Origins: parameters of the raw C function types use the erased `*AnyOrigin`,
# and the wrapper methods are generic over the origin (as in the V1 bindings).
# Pointers that DuckDB hands to Mojo (return values, struct fields, callback
# parameters) use the untracked origins.

def mojo_type(spec: Spec, base: str, indirection: int, const: bool, *, role: str) -> str:
    """Render a spec type as a Mojo type.

    ``role`` is ``param`` (wrapper / C function parameter) or ``foreign``
    (return value, struct field, callback parameter).
    """
    t = spec.mojo_name(base)
    if indirection == 0:
        return t
    if role == "param":
        outer = "ImmutAnyOrigin" if const and indirection == 1 else "MutAnyOrigin"
    else:
        outer = "ImmUntrackedOrigin" if const and indirection == 1 else "MutUntrackedOrigin"
    # `const T **` puts the const on T, the innermost pointer.
    for level in range(indirection - 1):
        inner = "ImmUntrackedOrigin" if const and level == 0 else "MutUntrackedOrigin"
        t = f"Pointer[{t}, {inner}]"
    return f"Pointer[{t}, {outer}]"


def return_type(spec: Spec, fn: dict) -> str:
    return mojo_type(
        spec, fn["return_type"], fn.get("return_pointer", 0), fn.get("return_const", False), role="foreign"
    )


def param_name(name: str) -> str:
    return name + "_" if name in MOJO_RESERVED_NAMES else name


def fn_pointer_type(spec: Spec, fn: dict, *, role: str) -> str:
    params = [
        mojo_type(spec, p["type"], p.get("indirection", 0), p.get("const", False), role=role)
        for p in (fn.get("parameters") or {}).values()
    ]
    return f'def({", ".join(params)}) thin abi("C") -> {return_type(spec, fn)}'


# ---------------------------------------------------------------------------
# Docs
# ---------------------------------------------------------------------------

def resolve_refs(spec: Spec, text: str) -> str:
    """Turn `[[name]]` references into the full C name (`duckdb_v2_name`)."""
    return re.sub(r"\[\[(\w+)\]\]", lambda m: spec.prefix + m.group(1), text)


def doc_lines(spec: Spec, text: str) -> list[str]:
    text = resolve_refs(spec, text or "").replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return [line.rstrip() for line in text.strip().split("\n")] if text.strip() else []


def comment_block(spec: Spec, text: str, prefix: str = "#") -> list[str]:
    return [f"{prefix} {line}".rstrip() for line in doc_lines(spec, text)]


def docstring(spec: Spec, indent: str, description: str, args: list[tuple[str, str]] | None = None) -> list[str]:
    lines = _ensure_summary_period(doc_lines(spec, description)) if description else []
    args = [(n, d) for n, d in (args or []) if d]
    if args:
        if lines:
            lines.append("")
        lines.append("Args:")
        for name, desc in args:
            dl = doc_lines(spec, desc)
            lines.append(f"    {name}: {dl[0] if dl else ''}")
            lines.extend(f"        {line}" if line else "" for line in dl[1:])
    if not lines:
        return []
    out = [f'{indent}"""']
    out.extend(f"{indent}{line}" if line else "" for line in lines)
    out.append(f'{indent}"""')
    return out


